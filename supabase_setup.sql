create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);
create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null check (category in ('books','notes','questions')),
  url text not null,
  description text default '',
  created_at timestamptz not null default now()
);
create table if not exists public.site_settings (
  id integer primary key check (id = 1),
  department_name text default 'MATHEMATICS DEPARTMENT',
  channel_name text default 'Aminur''s ClassRoom',
  youtube_url text default '',
  logo_url text default '',
  photo_url text default ''
);
insert into public.site_settings (id) values (1) on conflict (id) do nothing;

alter table public.admin_users enable row level security;
alter table public.resources enable row level security;
alter table public.site_settings enable row level security;

create or replace function public.is_site_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

drop policy if exists "Public can read resources" on public.resources;
create policy "Public can read resources" on public.resources for select using (true);
drop policy if exists "Admins can insert resources" on public.resources;
create policy "Admins can insert resources" on public.resources for insert with check (public.is_site_admin());
drop policy if exists "Admins can update resources" on public.resources;
create policy "Admins can update resources" on public.resources for update using (public.is_site_admin()) with check (public.is_site_admin());
drop policy if exists "Admins can delete resources" on public.resources;
create policy "Admins can delete resources" on public.resources for delete using (public.is_site_admin());

drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings" on public.site_settings for select using (true);
drop policy if exists "Admins can insert site settings" on public.site_settings;
create policy "Admins can insert site settings" on public.site_settings for insert with check (public.is_site_admin());
drop policy if exists "Admins can update site settings" on public.site_settings;
create policy "Admins can update site settings" on public.site_settings for update using (public.is_site_admin()) with check (public.is_site_admin());

